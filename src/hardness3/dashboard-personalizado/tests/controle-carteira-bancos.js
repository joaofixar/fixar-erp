'use strict';
const assert = require('assert');
const fs = require('fs');
const path = require('path');
const cp = require('child_process');
const model = require('../controle-carteira-bancos-model');
const payload = JSON.parse(process.argv[2] ? fs.readFileSync(process.argv[2], 'utf8') : cp.execFileSync('php', [path.join(__dirname, 'controle-carteira-bancos.php'), '--payload']));
const expected = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/controle-carteira-bancos-planilha.json'))).esperado;
const data = payload.controleCarteiraBancos;
const result = model.calculate(data);
assert.equal(result.garantiaCentavos, expected.garantiaCentavos);
for (const bank of result.bancos) {
  assert.equal(bank.saldoInicialCentavos, expected.bancos[bank.id].saldoInicialCentavos);
  assert.deepEqual(bank.pontos.map(({ data, saldoCentavos }) => ({ data, saldoCentavos })), expected.bancos[bank.id].pontos);
}
const itau = result.bancos.find(b => b.id === 'itau');
const bradesco = result.bancos.find(b => b.id === 'bradesco');
assert.equal(itau.primeiraData, '2026-11-11');
assert.equal(bradesco.primeiraData, '2026-11-04');
assert.equal(result.saldo7Centavos, result.bancos.reduce((sum, b) => sum + b.pontos[6].saldoCentavos, 0));
const changed = model.calculate(data, { itau: 0 });
assert.equal(changed.bancos.find(b => b.id === 'itau').saldoInicialCentavos - itau.saldoInicialCentavos, 300000000);
assert.equal(model.addDays('2026-12-31', 1), '2027-01-01');
assert.equal(model.addDays('2028-02-28', 1), '2028-02-29');
for (const value of [-1, Infinity, NaN, 1e12 + 1, 0.001, 0.00001, '100']) assert.equal(model.validGuarantee(value), false);
for (const value of [0, 0.29, 123.45, 999999999999.99, 1e12]) assert.equal(model.validGuarantee(value), true);
const tiny = { dataInicio: '2026-12-31', diasProjecao: 7, bancos: [{ id: 'teste', nome: '=DDE()', garantia: 0.20, carteiraCentavos: 30, vencimentos: { '2026-12-31': 10, '2027-01-02': 20 } }] };
const exact = model.calculate(tiny);
assert.equal(exact.bancos[0].primeiraData, '2026-12-31', 'Igualdade com a garantia já gera alerta');
assert.equal(exact.bancos[0].pontos[0].saldoCentavos, 0);
assert.equal(exact.bancos[0].pontos[1].saldoCentavos, 0, 'Dias sem vencimentos preservam saldo');
assert.equal(exact.bancos[0].saldoFinalCentavos, -20);
assert.equal(exact.bancos[0].recomporCentavos, 20);
const csv = model.csv(tiny, exact);
assert(csv.includes("'=DDE()"), 'Neutraliza fórmulas nos nomes');
assert(csv.includes('"-0,20"'), 'Valores negativos continuam numéricos');
assert(!csv.includes("'-0,20"));
assert.equal(csv.split('\r\n').length, 9);
console.log('OK: 270 projeções do navegador iguais à planilha, datas de alerta, sete dias inclusivos, edição, zero, virada do ano, centavos e CSV.');
