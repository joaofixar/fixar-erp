CREATE FUNCTION `D001_D005_Id`(xD001_Id int(11)) RETURNS int(11)
BEGIN
    DECLARE xD005_Id INT(11);
       SELECT T025_D005_Id
         INTO xD005_Id
         FROM D001
    LEFT JOIN T025 on T025_D015_Id=D001_D015_Id AND T025_D002_Id=D001_D002_Id
        WHERE D001_Id=xD001_Id
