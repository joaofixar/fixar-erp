CREATE TRIGGER `D001_trigger_alterar_preco_D009` BEFORE UPDATE ON `D001` FOR EACH ROW BEGIN
	IF NEW.D001_Preco_1 > 0 OR NEW.D001_Preco_2 > 0 OR NEW.D001_Preco_3 > 0 OR NEW.D001_Preco_4 > 0 THEN
		UPDATE D009 
			LEFT JOIN D049 ON D049_Id=D009_D049_Id
			LEFT JOIN D001 ON D001_Id=D049_D001_Id
			SET
				D009_Preco_1=IF(NEW.D001_Preco_1 > 0, NEW.D001_Preco_1, D009_Preco_1),
				D009_Preco_2=IF(NEW.D001_Preco_2 > 0, NEW.D001_Preco_2, D009_Preco_2),
				D009_Preco_3=IF(NEW.D001_Preco_3 > 0, NEW.D001_Preco_3, D009_Preco_3),
				D009_Preco_4=IF(NEW.D001_Preco_4 > 0, NEW.D001_Preco_4, D009_Preco_4)
		WHERE D001_Id=NEW.D001_Id;
	END IF;
END;