CREATE FUNCTION `D009_D005_Id`(xD009_Id INT(11)) RETURNS INT(11)
BEGIN
    DECLARE xD005_Id INT(11);
       SELECT D005_Id
         INTO xD005_Id
         FROM D009
    LEFT JOIN D049 ON D049_Id=D009_D049_Id
    LEFT JOIN D001 ON D001_Id=D049_D001_Id
    LEFT JOIN D005 ON D005_Id=D001_D005_Id
        WHERE D009_Id=xD009_Id
        LIMIT 1;
    IF xD005_Id IS NULL OR xD005_Id <= 0 THEN
          SELECT D005_Id
           INTO xD005_Id
            FROM D009
       LEFT JOIN D049 ON D049_Id=D009_D049_Id
       LEFT JOIN D001 ON D001_Id=D049_D001_Id
       LEFT JOIN T025 ON T025_D015_Id=D001_D015_Id AND T025_D002_Id=D001_D002_Id
       LEFT JOIN D005 ON D005_Id=T025_D005_Id
           WHERE D009_Id=xD009_Id
           LIMIT 1;
    END IF;
    RETURN xD005_Id;
END;
