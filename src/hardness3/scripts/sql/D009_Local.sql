CREATE FUNCTION `D009_Local`(xD009_Id INT(11),xD048_Id INT(11)) RETURNS VARCHAR(6) CHARSET utf8
BEGIN
    DECLARE xD004_Local VARCHAR(6);
    SELECT D004_Local
      INTO xD004_Local
      FROM D009
      LEFT JOIN T066 ON T066_D009_Id=D009_Id AND T066_D048_Id=xD048_Id
      LEFT JOIN D004 ON D004_Id=T066_D004_Id
     WHERE D009_Id=xD009_Id
     LIMIT 1;
  RETURN xD004_Local;
END;
