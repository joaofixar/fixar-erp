CREATE TRIGGER `D009_trigger_before_insert` BEFORE INSERT ON `D009` FOR EACH ROW BEGIN
  DECLARE xC004_IPV_Padrao DECIMAL(10,6) DEFAULT 1;
  DECLARE xC004_ICF_Padrao DECIMAL(10,6) DEFAULT 1;

  SELECT C004_IPV_Padrao, C004_ICF_Padrao INTO xC004_IPV_Padrao, xC004_ICF_Padrao FROM C004 WHERE C004_Id=NEW.D009_C004_Id;

  IF NEW.D009_IPV_1 <=0 THEN 
      SET NEW.D009_IPV_1 = xC004_IPV_Padrao;    
  END IF;  

  IF NEW.D009_ICF_1 <=0 THEN 
      SET NEW.D009_ICF_1 = xC004_ICF_Padrao;
  END IF; 
END;