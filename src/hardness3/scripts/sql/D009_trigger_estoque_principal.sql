CREATE TRIGGER D009_trigger_estoque_principal AFTER INSERT ON `D009` FOR EACH ROW BEGIN
  DECLARE xT066_Id INTEGER(10);
  DECLARE xD048_Id INTEGER(10);
  DECLARE xD004_Id INTEGER(10);
  DECLARE xCount INTEGER(255);
  SET xD048_Id = 1;
  SET xD004_Id = 0;

  SELECT COUNT(*) INTO xCount FROM D004;
  IF xCount = '1' THEN
 	SELECT D004_Id INTO xD004_Id FROM D004;
  END IF;

  SELECT T066_Id INTO xT066_Id FROM T066 WHERE T066_D048_Id=xD048_Id AND T066_D009_Id=NEW.D009_Id;
  IF xT066_Id IS NULL THEN
     INSERT INTO T066 (T066_D048_Id, T066_D009_Id, T066_D004_Id) VALUES (xD048_Id, NEW.D009_Id, xD004_Id);
  END IF;
END;
