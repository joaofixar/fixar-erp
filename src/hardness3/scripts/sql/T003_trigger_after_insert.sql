CREATE TRIGGER T003_trigger_after_insert AFTER INSERT ON `T003` FOR EACH ROW BEGIN
    DECLARE xT259_Id int(10) default 0;
	DECLARE xD085_Id int(10) default 0;
    INSERT INTO D085 (D085_D024_Id,D085_C007_Id,D085_Data,D085_Hora,D085_Mensagem,D085_Entidade,D085_Id_Entidade,D085_Flag_Manual,D085_T003_Id,D085_Flag_Tipo,D085_D013_Id) values (NEW.T003_D024_Id,NEW.T003_C007_Id_Vendedor_Interno,curdate(),curtime(),concat('Orcamento ',NEW.T003_Id),'T003',NEW.T003_Id,'N',NEW.T003_Id,'3',NEW.T003_D013_Id);
    SET xD085_Id = LAST_INSERT_ID();
    SELECT D085_T259_Id INTO xT259_Id FROM D085 WHERE (D085_T139_Id=NEW.T003_T139_Id AND IFNULL(D085_T139_Id,0) > 0) OR D085_Id=NEW.T003_D085_Id OR D085_T003_Id=NEW.T003_Id LIMIT 1;
	IF xT259_Id IS NULL THEN
		INSERT INTO T259 (T259_C007_Id, T259_D024_Id, T259_Data_Hora) VALUES (NEW.T003_C007_Id_Vendedor_Interno, NEW.T003_D024_Id, CURRENT_TIMESTAMP());
		SET xT259_Id = LAST_INSERT_ID();
	END IF;
	UPDATE D085 SET D085_T259_Id=xT259_Id WHERE D085_Id=xD085_Id;
    UPDATE D085 LEFT JOIN T003 ON T003_Id=D085_T003_Id LEFT JOIN T005 ON T003_Id=T005_T003_Id LEFT JOIN T007 ON T005_Id=T007_T005_Id SET D085_T005_Id = T005_Id, D085_T007_Id = T007_Id WHERE D085_T003_Id = NEW.T003_Id;
	UPDATE T259 SET T259_Data_Hora = CURRENT_TIMESTAMP() WHERE T259_Id = xT259_Id;
    INSERT INTO T260 (T260_Flag_Lido, T260_C007_Id, T260_T259_Id, T260_Data_Hora) VALUES ('S', NEW.T003_C007_Id_Vendedor_Interno, xT259_Id, CURRENT_TIMESTAMP());
END;