CREATE TRIGGER T007_trigger_after_insert AFTER INSERT ON `T007` FOR EACH ROW BEGIN
	DECLARE xD013_Id int(10) default 0;
	DECLARE xT003_Id int(10) default 0;
	DECLARE xT259_Id int(10) default 0;
	DECLARE xD085_Id int(10) default 0;
	SELECT T005_D013_Id, T005_T003_Id INTO xD013_Id, xT003_Id FROM T005 WHERE T005_Id=NEW.T007_T005_Id;
    INSERT INTO D085 (D085_D024_Id,D085_C007_Id,D085_Data,D085_Hora,D085_Mensagem,D085_Entidade,D085_Id_Entidade,D085_Flag_Manual,D085_T007_Id,D085_Flag_Tipo,D085_D013_Id) values (NEW.T007_D024_Id,NEW.T007_C007_Id_Vendedor_Interno,curdate(),curtime(),concat('Nota Fiscal ',NEW.T007_Numero_Nota_Fiscal),'T007',NEW.T007_Id,'N',NEW.T007_Id,'5',xD013_Id);
    SET xD085_Id = LAST_INSERT_ID();
    SELECT D085_T259_Id INTO xT259_Id FROM D085 WHERE D085_T005_Id=NEW.T007_T005_Id LIMIT 1;
	IF xT259_Id IS NULL THEN
		INSERT INTO T259 (T259_C007_Id, T259_D024_Id, T259_Data_Hora) VALUES (NEW.T007_C007_Id_Vendedor_Interno, NEW.T007_D024_Id, CURRENT_TIMESTAMP());
		SET xT259_Id = LAST_INSERT_ID();
	END IF;
	UPDATE D085 SET D085_T259_Id=xT259_Id WHERE D085_Id=xD085_Id;
    UPDATE D085 LEFT JOIN T007 ON T007_Id=D085_T007_Id LEFT JOIN T005 ON T005_Id=T007_T005_Id SET D085_T003_Id = T005_T003_Id, D085_T005_Id = T007_T005_Id WHERE D085_T007_Id = NEW.T007_Id;
    UPDATE D085 LEFT JOIN T005 ON T005_Id=D085_T005_Id LEFT JOIN T003 ON T003_Id=T005_T003_Id LEFT JOIN T007 ON T005_Id=T007_T005_Id SET D085_T003_Id = T005_T003_Id, D085_T007_Id = T007_Id WHERE D085_T005_Id = NEW.T007_T005_Id;
    UPDATE D085 LEFT JOIN T003 ON T003_Id=D085_T003_Id LEFT JOIN T005 ON T003_Id=T005_T003_Id LEFT JOIN T007 ON T005_Id=T007_T005_Id SET D085_T005_Id = T005_Id, D085_T007_Id = T007_Id WHERE D085_T003_Id = xT003_Id;
    UPDATE T259 SET T259_Data_Hora = CURRENT_TIMESTAMP() WHERE T259_Id = xT259_Id;
    INSERT INTO T260 (T260_Flag_Lido, T260_C007_Id, T260_T259_Id, T260_Data_Hora) VALUES ('S', NEW.T007_C007_Id_Vendedor_Interno, xT259_Id, CURRENT_TIMESTAMP());
END;