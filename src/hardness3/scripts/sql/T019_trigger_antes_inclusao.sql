CREATE TRIGGER `T019_trigger_antes_inclusao` BEFORE INSERT ON `T019` FOR EACH ROW BEGIN
	DECLARE xSaldo decimal(14,2) default 0;
  	DECLARE xD032_Id int(10) default 0;
    SELECT D014_D032_Id INTO xD032_Id FROM D014 WHERE D014_Id=NEW.T019_D014_Id;
	SET NEW.T019_D032_Id = xD032_Id;

	SELECT IFNULL(D007_Valor_Saldo,0) INTO xSaldo from D007 WHERE D007_Id=NEW.T019_D007_Id;
	SET NEW.T019_Saldo=xSaldo+NEW.T019_Valor_Lancamento;
END;
