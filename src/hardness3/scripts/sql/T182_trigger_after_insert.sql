CREATE TRIGGER T182_trigger_after_insert AFTER INSERT ON `T182` FOR EACH ROW BEGIN
	DECLARE xT259_Id int(10) default NULL;
	DECLARE xD085_Id int(10) default 0;

    INSERT INTO D085 (D085_D024_Id,D085_C007_Id,D085_Data,D085_Hora,D085_Mensagem,D085_Entidade,D085_Id_Entidade,D085_Flag_Manual,D085_T182_Id,D085_Flag_Tipo,D085_D013_Id)
    values(NEW.T182_D024_Id_Cliente,NEW.T182_C007_Id,curdate(),curtime(),concat('RMA ',NEW.T182_Id),'T182',NEW.T182_Id,'N',NEW.T182_Id,'4',NEW.T182_D013_Id_Cliente);
	SET xD085_Id = LAST_INSERT_ID();
	SELECT D085_T259_Id INTO xT259_Id FROM D085 LEFT JOIN T007 ON T007_Id=D085_T007_Id WHERE D085_D024_Id=NEW.T182_D024_Id_Cliente AND T007_Numero_Nota_Fiscal=NEW.T182_NF_Venda LIMIT 1;
	IF xT259_Id IS NULL THEN
		INSERT INTO T259 (T259_C007_Id, T259_D024_Id, T259_Data_Hora) VALUES (NEW.T182_C007_Id, NEW.T182_D024_Id_Cliente, CURRENT_TIMESTAMP());
		SET xT259_Id = LAST_INSERT_ID();
	END IF;
	UPDATE D085 SET D085_T259_Id=xT259_Id WHERE D085_Id=xD085_Id;
    UPDATE T259 SET T259_Data_Hora = CURRENT_TIMESTAMP() WHERE T259_Id = xT259_Id;
    INSERT INTO T260 (T260_Flag_Lido, T260_C007_Id, T260_T259_Id, T260_Data_Hora) VALUES ('S', NEW.T182_C007_Id, xT259_Id, CURRENT_TIMESTAMP());
END;