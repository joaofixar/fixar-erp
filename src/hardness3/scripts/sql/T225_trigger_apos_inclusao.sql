CREATE TRIGGER `T225_trigger_apos_inclusao` AFTER INSERT ON `T225` FOR EACH ROW BEGIN   
  DECLARE xD024_Id INT(10);
  DECLARE xD001_Id INT(10);
  DECLARE xCount INT;

  UPDATE D009 SET D009_Quantidade_OC=D009_Quantidade_OC_3(D009_Id, 0) where D009_Id=NEW.T225_D009_Id;
 
  SELECT T224_D024_Id, D049_D001_Id INTO xD024_Id, xD001_Id FROM T225 LEFT JOIN D009 ON D009_Id=T225_D009_Id LEFT JOIN D049 ON D049_Id=D009_D049_Id LEFT JOIN T224 ON T224_Id=T225_T224_Id WHERE T225_Id=NEW.T225_Id;
  SELECT COUNT(*) INTO xCount FROM T241 WHERE T241_D024_Id = xD024_Id AND T241_D001_Id = xD001_Id;
  IF xCount IS NULL OR xCount = 0 THEN
  	INSERT INTO T241 (T241_D024_Id, T241_D001_Id) values (xD024_Id, xD001_Id);
  END IF;
END;
